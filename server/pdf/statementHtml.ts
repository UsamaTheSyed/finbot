import { tokens } from "../../src/styles/tokens.js";
import { statementPeriod } from "../../src/domain/accountStatement.js";
import type { StatementData } from "../services/statements.js";
import { escapeHtml as e } from "./invoiceHtml.js";
import { invoicePdfStyles } from "./styles.js";
const money = (n: number) =>
  `PKR ${(n / 100).toLocaleString("en-PK", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
export function statementHtml(data: StatementData, fonts: string) {
  const { party, business } = data;
  return `<!doctype html><html lang="en"><head><meta charset="utf-8">
  <meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src 'unsafe-inline'; font-src data:">
  <title>Account Statement - ${e(party.name)}</title><style>${fonts}${invoicePdfStyles(tokens)}</style></head><body>
  <header><div><strong>${e(business.name)}</strong><p>${e(business.address)}</p><p>${e(business.email)}</p><p>${e(business.phone)}</p></div><div class="document-title"><h1>Account Statement</h1><p>${e(party.kind)}</p></div></header>
  <div class="info"><section><h2>${e(party.name)}</h2><p>${e(party.address)}</p><p>${e(party.email)}</p><p>${e(party.phone)}</p></section><section><h2>Statement Period</h2><p>${e(statementPeriod(data.range))}</p><p>Currency: PKR</p></section></div>
  <p class="caption">Business perspective: positive balance = party owes you; negative balance = you owe the party. Includes advances and refunds. Payments appear once on their payment date.</p>
  <table aria-label="Account statement"><colgroup><col style="width:14%"><col style="width:24%"><col style="width:20%"><col style="width:21%"><col style="width:21%"></colgroup><thead><tr><th>Date</th><th>Reference</th><th>Description</th><th>Movement</th><th>Balance</th></tr></thead><tbody>
  <tr><td>${e(data.range.from || "—")}</td><td colspan="3">Opening Balance</td><td>${money(data.openingMinor)}</td></tr>
  ${data.rows.map((r) => `<tr><td>${e(r.date)}</td><td>${e(r.reference)}</td><td>${e(r.label)}</td><td>${money(r.amountMinor)}</td><td>${money(r.balanceMinor)}</td></tr>`).join("")}
  ${!data.rows.length ? '<tr><td colspan="5">No account activity in this period.</td></tr>' : ""}
  </tbody></table><section class="summary"><h2>Statement Summary</h2><dl>
  ${[
    ["Opening Balance", data.openingMinor],
    ["Increases", data.increasesMinor],
    ["Decreases", data.decreasesMinor],
    ["Closing Balance", data.closingMinor],
  ]
    .map(([k, v]) => `<div><dt>${k}</dt><dd>${money(Number(v))}</dd></div>`)
    .join("")}
  </dl></section><p class="caption end">Generated by FinBot · Based on currently recorded ledger entries and their business dates. Drafts are excluded. This is an account statement, not a tax invoice.</p></body></html>`;
}
